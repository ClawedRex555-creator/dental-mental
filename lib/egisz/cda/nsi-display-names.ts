export function normalizeNmuCode(code: string): string {
  return code.trim().replace(/А/gi, "A").replace(/В/gi, "B").toUpperCase();
}

export function getNmuDisplayName(code: string): string | undefined {
  return NMU_DISPLAY_BY_CODE[normalizeNmuCode(code)];
}

/** Варианты для выбора в прайсе (код + каноническое имя НСИ) */
export function listNmuDentalOptions(): Array<{ code: string; name: string }> {
  return Object.entries(NMU_DISPLAY_BY_CODE)
    .map(([code, name]) => ({ code, name }))
    .sort((a, b) => a.code.localeCompare(b.code, "ru"));
}

/** Подсказать код НМУ по свободному названию услуги клиники */
export function suggestNmuCodeFromName(serviceName: string): string | undefined {
  const raw = serviceName.trim();
  if (!raw) return undefined;
  for (const hint of NMU_CODE_BY_NAME_HINT) {
    if (hint.re.test(raw)) return hint.code;
  }
  return undefined;
}

export function resolveMkb10DisplayName(code: string, fallbackText?: string): string {
  const normalized = code.trim().toUpperCase();
  const fromNsi = MKB10_DISPLAY_BY_CODE[normalized];
  if (fromNsi) return fromNsi;
  const cleaned = (fallbackText ?? "")
    .replace(new RegExp(`^${normalized}\\b\\s*`, "i"), "")
    .trim();
  return cleaned || normalized;
}

/**
 * Подбор пары code+displayName для CDA.
 * Имя всегда берётся из НСИ, если код известен — иначе ЕГИСЗ вернёт INVALID_ELEMENT_VALUE_NAME.
 *
 * Явный код из прайса (не равный fallback) важнее эвристики по названию.
 * Дефолтный код приёма + название «гигиена» → берём код гигиены по названию.
 */
export function resolveNmuService(input: {
  serviceCode?: string;
  serviceName?: string;
  fallbackCode: string;
  fallbackName: string;
}): { code: string; name: string } {
  const rawCode = input.serviceCode ? normalizeNmuCode(input.serviceCode) : "";
  const rawName = input.serviceName?.trim() ?? "";
  const fallbackCode = normalizeNmuCode(input.fallbackCode);

  const knownName = (code: string) => NMU_DISPLAY_BY_CODE[code];

  // 1) Явный код из прайса/медкарты (не дефолт) — доверяем, имя только из НСИ
  if (rawCode && knownName(rawCode) && rawCode !== fallbackCode) {
    return { code: rawCode, name: knownName(rawCode)! };
  }

  // 2) Подсказка по названию услуги клиники
  for (const hint of NMU_CODE_BY_NAME_HINT) {
    if (hint.re.test(rawName)) {
      const code = hint.code;
      return { code, name: knownName(code) ?? rawName };
    }
  }

  // 3) Известный код (в т.ч. дефолтный приём)
  if (rawCode && knownName(rawCode)) {
    return { code: rawCode, name: knownName(rawCode)! };
  }

  // 4) Неизвестный код + произвольное имя почти наверняка упадёт в ЕГИСЗ
  if (rawCode && rawName) {
    return { code: fallbackCode, name: input.fallbackName };
  }

  return {
    code: rawCode || fallbackCode,
    name: knownName(rawCode || fallbackCode) ?? input.fallbackName,
  };
}
